                const span = document.createElement("span");
                span.className = "err";
                span.textContent = invalido ? (c.tipo === "link" ? "Endereço não reconhecido. Use um link que comece com https://." : "Valor não reconhecido. Use, por exemplo, 45,90.") : "Preencha este campo.";
