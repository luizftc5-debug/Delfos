  function abrirModal(conteudoHTML, { aoMontar, aoFechar, classe = "" } = {}) {
    const backdrop = document.createElement("div");
    backdrop.className = "backdrop";
    backdrop.innerHTML = `<div class="modal ${classe}" role="dialog" aria-modal="true" tabindex="-1">${conteudoHTML}</div>`;
    const modal = backdrop.querySelector(".modal");
    // O título da janela é o nome dela para o leitor de tela.
    const titulo = modal.querySelector(".modal-title, .perfil-nome");
    if (titulo) {
      titulo.id = titulo.id || `janela-${Date.now().toString(36)}`;
      modal.setAttribute("aria-labelledby", titulo.id);
    }
    const origem = document.activeElement;
    document.body.appendChild(backdrop);
    document.body.style.overflow = "hidden";

    const focaveis = () => [...modal.querySelectorAll('a[href], button:not([disabled]), input:not([disabled]):not([type="hidden"]), select:not([disabled]), textarea:not([disabled]), [contenteditable="true"], [tabindex]:not([tabindex="-1"])')]
      .filter((x) => x.offsetParent !== null || x === document.activeElement);
    const fechar = (resultado) => {
      document.body.style.overflow = "";
      backdrop.remove();
      document.removeEventListener("keydown", onKey);
      // A volta do foco para quem abriu a janela: o teclado não se perde no topo da página.
      if (origem instanceof HTMLElement && document.contains(origem)) origem.focus({ preventScroll: true });
      aoFechar?.(resultado);
    };
    const onKey = (e) => {
      // Só a janela de cima responde (uma confirmação aberta sobre um formulário).
      if (backdrop !== [...document.querySelectorAll(".backdrop")].pop()) return;
      if (e.key === "Escape") { fechar(null); return; }
      // Tab circula dentro da janela aberta, sem escapar para a página atrás.
      if (e.key === "Tab") {
        const f = focaveis();
        if (!f.length) { e.preventDefault(); modal.focus(); return; }
        const primeiro = f[0];
        const ultimo = f[f.length - 1];
        if (e.shiftKey && (document.activeElement === primeiro || document.activeElement === modal)) { e.preventDefault(); ultimo.focus(); }
        else if (!e.shiftKey && document.activeElement === ultimo) { e.preventDefault(); primeiro.focus(); }
      }
    };

    backdrop.addEventListener("mousedown", (e) => { if (e.target === backdrop) fechar(null); });
    document.addEventListener("keydown", onKey);
    aoMontar?.(modal, fechar);
    // Se a própria janela não pôs o foco num campo, ele vai para a janela.
    if (!modal.contains(document.activeElement)) modal.focus({ preventScroll: true });
    return fechar;
  }

