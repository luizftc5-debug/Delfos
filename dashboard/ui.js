    /** O tema de fato na tela: "auto" segue o claro/escuro do sistema. */
    aplicado() {
      const v = tema.atual();
      if (v !== "auto") return v;
      return typeof matchMedia === "function" && matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark";
    },
    /** Põe o tema no <html> e a cor da barra do navegador no celular (theme-color). */
    pintar() {
      const t = tema.aplicado();
      document.documentElement.setAttribute("data-theme", t);
      let meta = document.querySelector('meta[name="theme-color"]');
      if (!meta && document.head) {
        meta = document.createElement("meta");
        meta.name = "theme-color";
        document.head.appendChild(meta);
      }
      meta?.setAttribute("content", t === "light" ? "#f4f5f1" : "#121413");
    },
    definir(v) {
      try { localStorage.setItem(tema.KEY, v); } catch { /* modo anônimo */ }
      tema.pintar();
    },
    iniciar() {
      tema.pintar();
      if (!tema.ouvindo && typeof matchMedia === "function") {
        tema.ouvindo = true;
        matchMedia("(prefers-color-scheme: light)").addEventListener?.("change", () => {
          if (tema.atual() === "auto") tema.pintar();
        });
      }
    },
